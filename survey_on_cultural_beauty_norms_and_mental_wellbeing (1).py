# ---------------------------------------------------------------------------
correlation(BeautyNorms_Score, SelfEsteem_Score, "BeautyNorms", "SelfEsteem")
correlation(BeautyNorms_Score, Anxiety_Score, "BeautyNorms", "Anxiety")

plot_scatter_with_trend(
    BeautyNorms_Score, SelfEsteem_Score,
    "BeautyNorms_Score", "SelfEsteem_Score",
    "Self-Esteem vs. Frequency of Experiencing Beauty Norms",
)
plot_scatter_with_trend(
    BeautyNorms_Score, Anxiety_Score,
    "BeautyNorms_Score", "Anxiety_Score",
    "Anxiety vs. Frequency of Experiencing Beauty Norms",
)

# ---------------------------------------------------------------------------
# 2. K-means clustering (k = 3)
# ---------------------------------------------------------------------------
cluster_and_plot(
    BeautyNorms_Score, SelfEsteem_Score,
    "BeautyNorms_Score", "SelfEsteem_Score",
    "K-Means Clustering of Self-Esteem vs Beauty Norms Scores",
)
cluster_and_plot(
    BeautyNorms_Score, Anxiety_Score,
    "BeautyNorms_Score", "Anxiety_Score",
    "K-Means Clustering of Anxiety vs Beauty Norms Scores",
)