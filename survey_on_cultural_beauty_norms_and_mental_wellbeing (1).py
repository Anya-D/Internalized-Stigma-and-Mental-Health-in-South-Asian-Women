import numpy as np
import matplotlib.pyplot as plt
from scipy import stats
from sklearn.cluster import KMeans

# ---------------------------------------------------------------------------
# Data (one value per participant, n = 29)
# ---------------------------------------------------------------------------
SelfEsteem_Score = [3.6, 3, 2.6, 3.9, 3.4, 2.7, 3.1, 2.9, 2.6, 4.3, 3.4, 3.3, 2, 3, 3.7,
                    3.7, 3.3, 4.1, 2.3, 3.5, 4.7, 2, 4.4, 2.8, 3.5, 2.3, 2.4, 4.6, 3.5]

Anxiety_Score = [1.714285714, 2.428571429, 1.857142857, 2.428571429, 4.428571429,
                 1.571428571, 2.285714286, 2.714285714, 1.857142857, 1.428571429,
                 1.714285714, 2.142857143, 3.428571429, 1.857142857, 1.714285714,
                 1.714285714, 1.714285714, 2.285714286, 3.714285714, 2.857142857,
                 1.142857143, 3.428571429, 1.714285714, 3.285714286, 1.857142857,
                 3.714285714, 2.285714286, 1.142857143, 2.142857143]

BeautyNorms_Score = [2.6875, 4, 2.125, 2.5, 2.0625, 2.3125, 2.4375, 2.75, 3.3125, 1.4375,
                     3.5, 2.3125, 3.875, 2.9375, 1.875, 2.375, 2.9375, 2.5625, 2.625,
                     2.5625, 1.8125, 3.625, 3.4375, 1.3125, 2.1875, 2.6875, 2.875,
                     1.1875, 1.625]

assert len(SelfEsteem_Score) == len(Anxiety_Score) == len(BeautyNorms_Score)

N_CLUSTERS = 3
RANDOM_STATE = 42


def correlation(x, y, x_name, y_name):
    """Print and return Pearson r and p-value."""
    r, p = stats.pearsonr(x, y)
    print(f"{x_name} vs {y_name}: r = {r:.2f}, p = {p:.3f} (n = {len(x)})")
    return r, p


def plot_scatter_with_trend(x, y, x_label, y_label, title):
    """Scatter plot of two scores with a least-squares trend line."""
    slope, intercept = np.polyfit(x, y, 1)
    xs = np.linspace(min(x), max(x), 100)

    plt.figure()
    plt.scatter(x, y, s=50)
    plt.plot(xs, slope * xs + intercept, color="red")
    plt.xlabel(x_label)
    plt.ylabel(y_label)
    plt.title(title)
    plt.grid(True)
    plt.show()


def cluster_and_plot(x, y, x_label, y_label, title, k=N_CLUSTERS):
    """K-means cluster two scores (x on horizontal axis, y on vertical axis)."""
    X = np.column_stack([x, y])  # column 0 -> x-axis, column 1 -> y-axis
    kmeans = KMeans(n_clusters=k, random_state=RANDOM_STATE, n_init=10)
    labels = kmeans.fit_predict(X)

    plt.figure()
    plt.scatter(X[:, 0], X[:, 1], c=labels, s=50, cmap="viridis")
    centers = kmeans.cluster_centers_
    plt.scatter(centers[:, 0], centers[:, 1], c="red", s=200, alpha=0.75, marker="X")
    plt.xlabel(x_label)
    plt.ylabel(y_label)
    plt.title(title)
    plt.grid(True)
    plt.show()
    return labels, centers


# ---------------------------------------------------------------------------
